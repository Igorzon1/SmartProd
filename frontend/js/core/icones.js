const SVG = "http://www.w3.org/2000/svg";

/**
 * <svg> de um ícone, decorativo (aria-hidden): o texto ao lado é que diz o que é.
 * icone("insumos") → <svg class="icone">…</svg>; nome desconhecido → null.
 */
export function icone(nome, classe = "icone") {
  const desenho = DESENHOS[nome];
  if (!desenho) return null;
  const doc = new DOMParser().parseFromString(
    `<svg xmlns="${SVG}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" `
      + `stroke-linecap="round" stroke-linejoin="round">${desenho}</svg>`,
    "image/svg+xml",
  );
  const svg = document.importNode(doc.documentElement, true);
  svg.setAttribute("class", classe);
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("focusable", "false");
  return svg;
}
