-- RF005: fichas técnicas (receitas) com ingredientes e passos de preparo.
-- SQL compatível com PostgreSQL (produção) e H2 (dev/testes).
CREATE TABLE fichas_tecnicas (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(120) NOT NULL,
    rendimento_padrao INTEGER      NOT NULL,
    criado_em         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_fichas_tecnicas_rendimento CHECK (rendimento_padrao > 0)
);

CREATE TABLE ficha_ingredientes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ficha_tecnica_id BIGINT        NOT NULL,
    insumo_id        BIGINT        NOT NULL,
    quantidade_base  NUMERIC(12,4) NOT NULL,
    eh_farinha       BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_ficha_ingredientes_ficha FOREIGN KEY (ficha_tecnica_id) REFERENCES fichas_tecnicas (id),
    CONSTRAINT fk_ficha_ingredientes_insumo FOREIGN KEY (insumo_id) REFERENCES insumos (id),
    CONSTRAINT ck_ficha_ingredientes_quantidade CHECK (quantidade_base > 0)
);

CREATE TABLE passos_preparo (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ficha_tecnica_id BIGINT        NOT NULL,
    ordem            INTEGER       NOT NULL,
    etapa            VARCHAR(120)  NOT NULL,
    descricao        VARCHAR(1000) NOT NULL,
    duracao_segundos INTEGER,
    CONSTRAINT fk_passos_preparo_ficha FOREIGN KEY (ficha_tecnica_id) REFERENCES fichas_tecnicas (id),
    CONSTRAINT ck_passos_preparo_ordem CHECK (ordem > 0)
);

-- RNF-D002: índices nas colunas de consulta frequente.
CREATE INDEX idx_fichas_tecnicas_nome ON fichas_tecnicas (nome);
CREATE INDEX idx_ficha_ingredientes_ficha ON ficha_ingredientes (ficha_tecnica_id);
CREATE INDEX idx_ficha_ingredientes_insumo ON ficha_ingredientes (insumo_id);
CREATE INDEX idx_passos_preparo_ficha ON passos_preparo (ficha_tecnica_id);